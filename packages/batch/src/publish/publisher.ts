// 公開先への送り出し。まだ送る先を決めていない。
//
// <VAR>/site/ が公開する中身そのもの。ここから先の選択肢は二つある。
//
//   Workers Static Assets  wrangler deploy で site ごと上げる。変わっていない
//                          ファイルはアップロードされない（ハッシュで照合される）ので、
//                          作品が増えても上がるのは増えた分だけ。動的な処理は要らない。
//   R2 + Worker            作品ごとに PUT で足していく。取り消しや差し替えが細かくできるが、
//                          Worker を一つ書いて R2 の前に置く必要がある。
//
// どちらでも、ビルドの仕組み（build.ts / site.ts）は変わらない。作品と
// エンジンは一度ビルドしたら中身が変わらず、名前も変わらないため。
//
// TODO: どちらかを選び、ここに実装する。失敗しても <VAR>/site/ は壊さず、
// 生成し直さずに送り直せるようにする。

export interface Publisher {
    readonly name: string;
    /** 組み立て済みの公開物を送る。送り終えるまで、今出ているサイトは壊さない。 */
    publish(siteDir: string): Promise<void>;
}
